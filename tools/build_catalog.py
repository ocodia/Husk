#!/usr/bin/env python3
"""Generate the committed human/browser views of docs/components.json (stdlib only)."""
import argparse
from collections import Counter
from html import escape
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABELS = {'native': 'Native recipe', 'foundation': 'Foundation', 'planned': 'Planned'}


def generate():
    data = json.loads((ROOT / 'docs/components.json').read_text())
    entries = data['components']
    ids = [item['id'] for item in entries + data['huskComponents']]
    if len(ids) != len(set(ids)):
        raise ValueError('Component IDs must be unique.')
    for item in entries:
        if item['status'] not in LABELS or item['phase'] not in range(1, 6):
            raise ValueError(f'Invalid status/phase: {item["id"]}')
        for key in ['name', 'category', 'reference', 'husk', 'contract', 'acceptance']:
            if not item.get(key):
                raise ValueError(f'{item["id"]} is missing {key}')
    md = ['<!-- Generated by tools/build_catalog.py; edit components.json. -->', '# Component catalogue', '',
          f'Reviewed {data["reviewed"]}: [Web Awesome reference catalogue]({data["reference"]}). '
          f'{len(entries)} reference entries and {len(data["huskComponents"])} existing Husk primitives.', '',
          data['description'], '',
          'Delivery phases and the stable-release gate are in [ROADMAP.md](../ROADMAP.md). '
          'Examples are minimal structures, not complete applications. Native/foundation entries still need the listed release evidence. '
          'Proposed widgets have contracts instead of pretend live demos.', '', '## Existing Husk primitives', '']
    cards = []
    for item in data['huskComponents']:
        md += [f'### {item["id"]}', '', f'**Foundation · {item["mode"]}.** {item["contract"]}', '',
               '```html', item['example'], '```', '', '[Current API](reference.md)', '']
    for category in dict.fromkeys(item['category'] for item in entries):
        md += [f'## {category}', '']
        for item in [entry for entry in entries if entry['category'] == category]:
            label = LABELS[item['status']]
            md += [f'### {item["name"]}', '', f'**{label} · Phase {item["phase"]}.** Husk route: `{item["husk"]}`.', '',
                   item['contract'], '', f'**Acceptance work:** {item["acceptance"]}', '']
            if item.get('example'):
                md += ['```html', item['example'], '```', '']
            if item.get('exampleNote'):
                md += [item['exampleNote'], '']
            md += [f'[Reference component]({item["reference"]}) · [Specification template](component-template.md)', '']
            example = f'<pre><code>{escape(item["example"])}</code></pre>' if item.get('example') else '<p>No runnable Husk component yet. This is a proposed contract.</p>'
            cards.append(f'''<details id="{item['id']}" data-component data-category="{escape(category)}" data-status="{item['status']}">
  <summary>{escape(item['name'])} — {label} · Phase {item['phase']}</summary>
  <p><strong>{escape(category)}</strong> · <code>{escape(item['husk'])}</code></p>
  <p>{escape(item['contract'])}</p>
  <p><strong>Acceptance work:</strong> {escape(item['acceptance'])}</p>
  {example}
  <p><a href="{item['reference']}">Reference component</a> · <a href="../docs/component-template.md">Specification template</a></p>
</details>''')
    counts=Counter(item['status'] for item in entries)
    options=''.join(f'<option>{escape(category)}</option>' for category in dict.fromkeys(item['category'] for item in entries))
    html=f'''<!doctype html>
<!-- Generated by tools/build_catalog.py; edit docs/components.json. -->
<html lang="en">
<head>
  <meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="Explore Husk component coverage, native recipes and planned enhancement contracts.">
  <title>Component explorer — Husk</title>
  <link rel="stylesheet" href="../css/husk.css"><link rel="stylesheet" href="examples.css">
  <script src="catalog.js" defer></script>
</head>
<body>
  <h-skip-link><a href="#main">Skip to component explorer</a></h-skip-link>
  <header><p><a href="index.html">Husk / Examples</a></p><h1>Component explorer</h1><p>Complete scope. Native foundations. Explicit contracts.</p></header>
  <nav aria-label="Examples"><ul><li><a href="index.html">Overview</a></li><li><a href="components.html" aria-current="page">Components</a></li><li><a href="patterns.html">Recipes</a></li><li><a href="themes.html">Themes</a></li><li><a href="../workspace.html">Workspace</a></li></ul></nav>
  <main id="main" tabindex="-1">
    <h-stack>
      <section aria-labelledby="scope-title"><h2 id="scope-title">Understand what is available</h2>
        <p>{len(entries)} reference entries: {counts['native']} native recipes, {counts['foundation']} foundation routes, {counts['planned']} planned enhancements. Reviewed {data['reviewed']}.</p>
        <p>Native recipes are platform building blocks, not feature parity. Foundation routes use existing Husk primitives. Planned names are proposals, not registered elements. Release evidence is tracked separately.</p>
        <p><a href="../docs/reference.md">Current API</a> · <a href="../ROADMAP.md">Delivery roadmap</a> · <a href="../docs/components.json">Machine-readable inventory</a></p>
      </section>
      <form id="catalog-filter" role="search" aria-label="Filter component catalogue" hidden>
        <h-grid>
          <h-field><label for="query">Find a component</label><input id="query" type="search" placeholder="Try tabs, date or progress"></h-field>
          <h-field><label for="category">Category</label><select id="category"><option value="">All categories</option>{options}</select></h-field>
          <h-field><label for="status">Implementation</label><select id="status"><option value="">All statuses</option><option value="native">Native recipe</option><option value="foundation">Foundation</option><option value="planned">Planned</option></select></h-field>
        </h-grid>
        <button type="reset">Clear filters</button>
      </form>
      <p id="catalog-count" role="status">{len(entries)} components shown.</p>
      <p id="catalog-empty" hidden>No matching components. Change the search or clear the filters.</p>
      <section aria-label="Component contracts">{''.join(cards)}</section>
      <section aria-labelledby="primitives-title"><h2 id="primitives-title">Husk's own primitives</h2>
        <p>{', '.join('<code>'+escape(item['id'])+'</code>' for item in data['huskComponents'])}.</p>
        <p><a href="patterns.html">See working compositions</a> and <a href="../docs/reference.md">read the implemented API</a>.</p>
      </section>
    </h-stack>
  </main>
  <footer><p>Husk · HTML conventions, accessible interaction, themeable foundations.</p></footer>
</body>
</html>
'''
    return {'docs/components.md':'\n'.join(md).rstrip()+'\n', 'examples/components.html':html}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Fail if committed generated files differ.')
    args=parser.parse_args()
    stale=[]
    for filename, content in generate().items():
        path=ROOT/filename
        if args.check:
            if not path.exists() or path.read_text()!=content: stale.append(filename)
        else:
            path.write_text(content)
    if stale: raise SystemExit('Stale catalogue output: '+', '.join(stale)+'. Run python3 tools/build_catalog.py')
    print('Catalogue views are current.' if args.check else 'Generated catalogue documentation and explorer.')

if __name__=='__main__': main()
